"""Show profiling — measure a show's structural traits and derive question-type quotas.

Pipeline step 0 of the golden-set pipeline (eval-loop-automation, D1):
measure structural traits via fixed SQL, derive a question-type quota
matrix from a static, human-readable rule table, and write a per-show
profile JSON that `build_golden_set.py --profile` consumes.

The profile is intentionally a plain JSON file: it MUST be manually
editable (edit quotas / metrics by hand and feed it straight back into
generation). No LLM is involved in quota decisions — rules below are the
whole story.

QUOTA RULE TABLE (static, D1)
    R1  guests_coverage < 0.10   → guest_find = 0, its base quota is
                                    redistributed to fact (larger half)
                                    and cross_episode (remainder)
    R2  summary_done_ratio < 0.5 → summary_overview = 0 (dropped, no
                                    redistribution — unanswerable type)
    R3  playlist_titles == 0     → playlist_enum = 0 (dropped)

`recurring_segments` is a placeholder hook for future structured-segment
extraction (台通推歌環節 etc.) — always emitted as [] here, never read.

`multi_turn_handcraft` quota is NOT auto-generated by build_golden_set;
it marks how many multi-turn items the human co-drafting pass should add.

Usage (prod DB via DATABASE_URL override):
    DATABASE_URL=postgresql://... python -m backend.eval.scripts.show_profile \
        --show-id e0f4a4d4-.... --show-slug yi-jia-yi

Defaults to backend/.env DATABASE_URL when no override is given.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

from dotenv import load_dotenv

REPO_ROOT = Path(__file__).resolve().parents[3]

# Base quota matrix before rules apply. Sums to 42 auto-generated + 2 handcraft.
# For a no-guest no-playlist show (e.g. 壹加壹) rules land the auto total at 40.
BASE_QUOTAS = {
    "fact": 10,
    "deep_dive": 8,
    "cross_episode": 6,
    "summary_overview": 4,
    "date_find": 3,
    "negative": 4,
    "code_switch": 2,
    "guest_find": 3,
    "playlist_enum": 2,
    "multi_turn_handcraft": 2,
}

GUESTS_COVERAGE_MIN = 0.10
SUMMARY_DONE_MIN = 0.5


def derive_quotas(metrics: dict) -> dict:
    """Apply the static rule table (R1-R3 above) to BASE_QUOTAS."""
    quotas = dict(BASE_QUOTAS)

    # R1: too few guest episodes → guest_find unanswerable at quota scale;
    # redistribute so total question pressure on core types is preserved.
    if metrics["guests_coverage"] < GUESTS_COVERAGE_MIN:
        freed = quotas["guest_find"]
        quotas["guest_find"] = 0
        larger_half = freed - freed // 2
        quotas["fact"] += larger_half
        quotas["cross_episode"] += freed - larger_half

    # R2: summaries not ready → summary questions would be unanswerable.
    if metrics["summary_done_ratio"] < SUMMARY_DONE_MIN:
        quotas["summary_overview"] = 0

    # R3: no playlist-pattern titles → nothing to enumerate.
    if metrics["playlist_titles"] == 0:
        quotas["playlist_enum"] = 0

    return quotas


def compute_en_char_ratio(texts: Iterable[str]) -> float:
    """Ratio of ASCII letters to non-whitespace characters across texts."""
    en = 0
    total = 0
    for t in texts:
        stripped = re.sub(r"\s", "", t)
        total += len(stripped)
        en += len(re.findall(r"[A-Za-z]", stripped))
    return round(en / total, 4) if total else 0.0


def build_profile(show_id: str, slug: str, metrics: dict) -> dict:
    """Assemble the full profile document (schema per Implementation Contract)."""
    return {
        "show_id": show_id,
        "slug": slug,
        "measured_at": datetime.now(timezone.utc).isoformat(),
        "metrics": metrics,
        "recurring_segments": [],
        "quotas": derive_quotas(metrics),
    }


REQUIRED_PROFILE_KEYS = ("show_id", "slug", "measured_at", "metrics", "recurring_segments", "quotas")


def load_profile(path: Path | str) -> dict:
    """Load and validate a profile JSON (possibly hand-edited).

    Used by build_golden_set.py --profile; raises ValueError with the
    offending key so a bad hand edit fails loudly instead of generating
    a skewed batch.
    """
    profile = json.loads(Path(path).read_text(encoding="utf-8"))
    for key in REQUIRED_PROFILE_KEYS:
        if key not in profile:
            raise ValueError(f"profile missing required key: {key}")
    unknown = set(profile["quotas"]) - set(BASE_QUOTAS)
    if unknown:
        raise ValueError(f"profile has unknown quota types: {sorted(unknown)}")
    for qtype, n in profile["quotas"].items():
        if not isinstance(n, int) or n < 0:
            raise ValueError(f"quota {qtype} must be a non-negative int, got {n!r}")
    return profile


async def measure(database_url: str, show_id: str, sample_n: int) -> dict:
    """Run the fixed SQL measurements against the given DB."""
    from sqlalchemy import text
    from sqlalchemy.ext.asyncio import create_async_engine

    engine = create_async_engine(database_url)
    try:
        async with engine.connect() as conn:
            row = (
                await conn.execute(
                    text(
                        """
                        SELECT
                          count(*) AS total,
                          count(*) FILTER (WHERE jsonb_array_length(guests) > 0) AS with_guests,
                          count(*) FILTER (WHERE title LIKE '%歌單%') AS playlist_titles,
                          count(*) FILTER (WHERE ai_summary_status = 'done') AS summary_done
                        FROM episodes
                        WHERE show_id = :sid
                        """
                    ),
                    {"sid": show_id},
                )
            ).one()
            if row.total == 0:
                raise SystemExit(f"[fatal] show {show_id} has no episodes")

            sample_texts = (
                await conn.execute(
                    text(
                        """
                        WITH sampled AS (
                          SELECT t.id
                          FROM episodes e
                          JOIN transcripts t ON t.episode_id = e.id AND t.status = 'completed'
                          WHERE e.show_id = :sid
                          ORDER BY random()
                          LIMIT :n
                        )
                        SELECT string_agg(c.text, '') AS full_text
                        FROM transcript_chunks c
                        JOIN sampled s ON c.transcript_id = s.id
                        GROUP BY c.transcript_id
                        """
                    ),
                    {"sid": show_id, "n": sample_n},
                )
            ).scalars().all()
    finally:
        await engine.dispose()

    return {
        "total_episodes": row.total,
        "guests_coverage": round(row.with_guests / row.total, 4),
        "playlist_titles": row.playlist_titles,
        "summary_done_ratio": round(row.summary_done / row.total, 4),
        "en_char_ratio_sample": compute_en_char_ratio(t for t in sample_texts if t),
        "en_char_sample_n": len(sample_texts),
    }


def _normalize_async_url(url: str) -> str:
    if url.startswith("postgresql://"):
        return url.replace("postgresql://", "postgresql+asyncpg://", 1)
    return url


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Measure show traits → profile JSON")
    parser.add_argument("--show-id", required=True, help="Show UUID")
    parser.add_argument("--show-slug", required=True, help="Lowercase slug (profile filename)")
    parser.add_argument(
        "--database-url",
        default=None,
        help="Override DATABASE_URL (defaults to env / backend/.env)",
    )
    parser.add_argument("--sample-n", type=int, default=20, help="Episodes sampled for en-char ratio")
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=REPO_ROOT / "backend" / "eval" / "datasets" / "profiles",
        help="Directory for {slug}.json output",
    )
    args = parser.parse_args(argv)

    database_url = args.database_url or os.environ.get("DATABASE_URL", "")
    if not database_url:
        load_dotenv(REPO_ROOT / "backend" / ".env")
        database_url = os.environ.get("DATABASE_URL", "")
    if not database_url:
        print("[fatal] no DATABASE_URL (flag, env, or backend/.env)", file=sys.stderr)
        return 2

    metrics = asyncio.run(
        measure(_normalize_async_url(database_url), args.show_id, args.sample_n)
    )
    profile = build_profile(args.show_id, args.show_slug, metrics)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    out_path = args.out_dir / f"{args.show_slug}.json"
    out_path.write_text(
        json.dumps(profile, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    print(f"[metrics] {json.dumps(metrics, ensure_ascii=False)}", file=sys.stderr)
    print(f"[quotas]  {json.dumps(profile['quotas'], ensure_ascii=False)}", file=sys.stderr)
    print(f"[ok] wrote profile → {out_path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
